/* ============================================================
   RGB-ingredient skin factory
   ============================================================
   Every entry in RGB_RECIPE_SKINS is a tiny descriptor:

     { id, name, price, r, g, b }

   `r`, `g`, `b` ∈ [0,1] are the "recipe" weights — how much of each
   pure channel ends up in the result. The factory below turns that
   into a 10-colour palette by:

     - using the recipe colour at full brightness as the headline
       swatch,
     - dimming it to 70 %, 55 % and 40 % to give darker shades,
     - and adding white-mix variants (+25, +60, +100 per channel,
       clamped at 255) for the lighter tints.

   The accent (used for HUD glow, CTAs, etc.) is the headline swatch.
   ============================================================ */

/* Clamp + format a 0..255 integer as a two-char hex byte. */
function _rgbByte(n){
  const v = Math.max(0, Math.min(255, Math.round(n)));
  const s = v.toString(16);
  return s.length < 2 ? "0" + s : s;
}
/* Pack three 0..255 channels into a #rrggbb literal. */
function _rgbHex(r, g, b){
  return "#" + _rgbByte(r) + _rgbByte(g) + _rgbByte(b);
}
/* Single palette entry: scale the recipe by `factor`, then add a
   flat `white` value to every channel (for tints). Both knobs are
   clamped at 0..255 by _rgbByte. */
function _rgbMix(base, factor, white){
  return _rgbHex(
    base[0] * factor + white,
    base[1] * factor + white,
    base[2] * factor + white,
  );
}
/* Build the 10-colour palette for an (r,g,b) recipe. The order is
   tuned so the first 6 entries (which the shop swatch shows) hit a
   nice spread of dim/bright/tinted variations. */
function _makeRgbPalette(r, g, b){
  const base = [r * 255, g * 255, b * 255];
  return [
    _rgbMix(base, 1.00,   0),  // headline
    _rgbMix(base, 0.70,   0),  // dim
    _rgbMix(base, 1.00,  60),  // tint
    _rgbMix(base, 0.85,  25),  // bright dim
    _rgbMix(base, 0.55,   0),  // dark
    _rgbMix(base, 1.00, 100),  // pale tint
    _rgbMix(base, 0.92,   0),  // slight dim
    _rgbMix(base, 0.40,   0),  // very dark
    _rgbMix(base, 0.95,  40),  // medium tint
    _rgbMix(base, 1.00,  30),  // bright with hint
  ];
}

