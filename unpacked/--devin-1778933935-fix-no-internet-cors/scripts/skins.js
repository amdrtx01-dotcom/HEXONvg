/* ============================================================
   HEXON BETA — Piece skins
   ============================================================
   A "skin" is a named palette + accent colour that re-paints every
   piece, tray cell, board cell, and shop preview. Skins live in
   state.skins (equipped + unlocked) and are persisted via
   storage.js. Players unlock new skins from the in-game shop.

   This file is split into two layers:

     1. Hand-crafted "themed" skins (default, neon, aurora, …) that
        ship with bespoke 10-colour palettes and unique SVG glyphs.

     2. A procedurally-generated "RGB ingredient" family — every skin
        is described by three weights (r, g, b ∈ [0,1]) representing
        how much of each pure colour channel goes into the recipe. The
        palette is generated by varying brightness / white-mix while
        keeping the recipe ratio intact, so the skin always reads as
        "this much red + this much green + this much blue". The icon
        shows the three pure-channel drops sized by their weight plus
        the resulting mixed colour — no two recipes look the same.

   Adding a themed skin: append an entry to SKINS with a unique id,
   a name, a price in HEX coins, and a 6+ colour palette. Adding an
   RGB recipe skin: append a descriptor to RGB_RECIPE_SKINS and the
   factory below will mint the palette + icon automatically.
   ============================================================ */
