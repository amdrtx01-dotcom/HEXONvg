/* Default builder for any RGB-recipe skin. Draws three pure-channel
   drops sized by the recipe weights — pure red top-left, pure green
   top-right, pure blue bottom — overlapping in the middle. A small
   centre dot shows the actual resulting colour from the skin's
   palette so the player can match icon → swatch at a glance. Drops
   whose weight is essentially zero are skipped so a "pure red" recipe
   shows just the red drop instead of three tiny dots. */
function _rgbRecipeIcon(skin){
  const rec = skin && skin.rgb;
  if(!rec) return SKIN_ICON_BUILDERS.default(skin.palette);
  /* Drop sizes scale linearly with weight, but clamp at a minimum
     visible radius so even a 5 % ingredient still reads. */
  const dropRadius = (w) => 2.4 + Math.max(0, Math.min(1, w)) * 4.6;
  const dropOpacity = (w) => 0.45 + Math.max(0, Math.min(1, w)) * 0.45;
  /* The three "ingredient" pots sit at the corners of a triangle;
     they overlap in the middle so additive mixing reads visually. */
  const drops = [];
  if(rec.r > 0.03) drops.push(
    '<circle cx="8"  cy="9"  r="' + dropRadius(rec.r).toFixed(2) +
    '" fill="#ff1f3a" opacity="' + dropOpacity(rec.r).toFixed(2) + '"/>'
  );
  if(rec.g > 0.03) drops.push(
    '<circle cx="16" cy="9"  r="' + dropRadius(rec.g).toFixed(2) +
    '" fill="#21d96a" opacity="' + dropOpacity(rec.g).toFixed(2) + '"/>'
  );
  if(rec.b > 0.03) drops.push(
    '<circle cx="12" cy="17" r="' + dropRadius(rec.b).toFixed(2) +
    '" fill="#3a8fff" opacity="' + dropOpacity(rec.b).toFixed(2) + '"/>'
  );
  /* The mixed-result dot — uses the skin's own headline colour so it
     looks like the "output" of the three ingredients. A thin white
     ring lifts it off the overlapping drops. */
  const result = (skin.palette && skin.palette[0]) || "#888";
  return (
    '<svg viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">' +
      drops.join("") +
      '<circle cx="12" cy="12" r="2.4" fill="' + result + '" stroke="rgba(255,255,255,.7)" stroke-width="0.7"/>' +
    '</svg>'
  );
}

/* Build the icon SVG string for a skin. Returns "" if the id is
   unknown so callers can do `if (svg) container.innerHTML = svg;`. */
function skinIconSvg(id){
  const skin = SKINS[id];
  if(!skin) return "";
  const build = SKIN_ICON_BUILDERS[id];
  if(build) return build(skin.palette);
  if(skin.rgb) return _rgbRecipeIcon(skin);
  return SKIN_ICON_BUILDERS.default(skin.palette);
}

/* ============================================================
   Rarity tiers
   ============================================================
   The catalogue is large (80+ skins) — a flat grid of swatches makes
   it hard for the player to tell "this is a cheap starter palette"
   apart from "this is the rare gold/galaxy headline skin". A rarity
   system gives every card a coloured badge + glow that scales with
   price, plus a sort key so the shop grid climbs from common → mythic
   as you scroll.

   Tiers are derived from skin.price unless the skin itself sets an
   explicit `rarity` field. The thresholds were picked so the existing
   prices fall into roughly even buckets:

     - starter  : the free default palette (price = 0)
     - common   : 1 .. 1199 HEX
     - rare     : 1200 .. 2199 HEX
     - epic     : 2200 .. 4499 HEX
     - legend   : 4500 .. 7999 HEX
     - mythic   : 8000+ HEX

   `accent` controls the badge background + card border glow. `label`
   is the short Ukrainian word shown on the badge. */
const RARITY_TIERS = [
  { id: "starter", weight: 0, minPrice:    0, accent: "#6c7390", label: "Стартова"    },
  { id: "common",  weight: 1, minPrice:    1, accent: "#9aa0b8", label: "Звичайна"    },
  { id: "rare",    weight: 2, minPrice: 1200, accent: "#24bdff", label: "Рідкісна"    },
  { id: "epic",    weight: 3, minPrice: 2200, accent: "#a766ff", label: "Епічна"      },
  { id: "legend",  weight: 4, minPrice: 4500, accent: "#ffb454", label: "Легендарна"  },
  { id: "mythic",  weight: 5, minPrice: 8000, accent: "#f25c8e", label: "Міфічна"     },
];
const RARITY_BY_ID = Object.fromEntries(RARITY_TIERS.map(t => [t.id, t]));

/* Map a skin id to its rarity descriptor. The explicit `rarity` field
   on a skin wins over price-based inference so curated hand-crafted
   palettes can be promoted (e.g. neon is "common" by price but
   shouldn't sit alongside the boring mono tints). */
function skinRarity(id){
  const skin = SKINS[id];
  if(!skin) return RARITY_BY_ID.starter;
  if(skin.rarity && RARITY_BY_ID[skin.rarity]) return RARITY_BY_ID[skin.rarity];
  const price = skin.price | 0;
  let tier = RARITY_BY_ID.starter;
  for(const t of RARITY_TIERS){
    if(price >= t.minPrice) tier = t;
  }
  return tier;
}

/* Explicit rarity bumps for hand-crafted themed skins. Default is
   always the starter tier — every other entry steps up at least one
   notch from where price alone would place it, because each themed
   skin has bespoke art and feels more special than a price-equivalent
   RGB recipe. */
SKINS.default.rarity = "starter";
SKINS.mono.rarity    = "common";
SKINS.neon.rarity    = "rare";
SKINS.aurora.rarity  = "rare";
SKINS.ocean.rarity   = "epic";
SKINS.pastel.rarity  = "epic";
SKINS.sunset.rarity  = "legend";
SKINS.ember.rarity   = "legend";
SKINS.galaxy.rarity  = "mythic";

/* The list order used by the shop grid. Default sits at the top as
   the "equipped"/starter card, then the catalogue is sorted by rarity
   weight (ascending — common first, mythic last) and inside each tier
   by price. This makes the climb to "Міфічна" a visible progression
   instead of a flat dump of palettes. */
const _allSkinIds = ["neon","aurora","ocean","pastel","sunset","ember","galaxy","mono"]
  .concat(RGB_RECIPE_SKINS.map(r => r.id));
_allSkinIds.sort((a, b) => {
  const ra = skinRarity(a), rb = skinRarity(b);
  if(ra.weight !== rb.weight) return ra.weight - rb.weight;
  return (SKINS[a].price | 0) - (SKINS[b].price | 0);
});
const SHOP_SKIN_ORDER = ["default"].concat(_allSkinIds);

function currentSkinId(){
  return (state.skins && state.skins.equipped) || "default";
}
function currentSkin(){
  return SKINS[currentSkinId()] || SKINS.default;
}
function currentPalette(){
  return currentSkin().palette;
}
function isSkinUnlocked(id){
  return !!(state.skins && Array.isArray(state.skins.unlocked) && state.skins.unlocked.indexOf(id) >= 0);
}
function unlockSkin(id){
  if(!SKINS[id]) return false;
  if(!state.skins) state.skins = { equipped:"default", unlocked:["default"] };
  if(!Array.isArray(state.skins.unlocked)) state.skins.unlocked = ["default"];
  if(state.skins.unlocked.indexOf(id) < 0) state.skins.unlocked.push(id);
  return true;
}
function equipSkin(id){
  if(!SKINS[id]) return false;
  if(!isSkinUnlocked(id)) return false;
  state.skins.equipped = id;
  applySkinAccent();
  return true;
}
/* Push the equipped skin's accent into a CSS custom property so the
   menu, HUD, and shop can tint themselves to match the current
   piece palette without re-reading the JS state. */
function applySkinAccent(){
  const s = currentSkin();
  document.documentElement.style.setProperty("--skin-accent", s.accent || "#7c5cff");
}
